/** `reason` 为失败原因的文案 key，展示时按当前语言翻译后填入 `message` 参数。 */
type Status = (TranslationMessage & { error?: boolean; reason?: TranslationKey }) | null

type Translate = ReturnType<typeof useTranslate>

const statusText = (t: Translate, status: Status): string | undefined =>
  status ? t(status.key, status.reason ? { message: t(status.reason) } : status.params) : undefined

const statusTone = (status: Status): 'error' | undefined => (status?.error ? 'error' : undefined)

/** 导出失败附带原因：预期的错误用对应文案作原因，其他错误用错误信息。 */
const errorStatus = (key: TranslationKey, error: unknown): Status => ({
  key,
  ...(error instanceof BackupError
    ? { reason: error.key }
    : { params: { message: error instanceof Error ? error.message : String(error) } }),
  error: true,
})

/** 选文件后先提示覆盖；确认后才检查文件并执行导入，任何错误都提示导入失败。 */
const useHistoryImport = () => {
  const [file, setFile] = useState<File | null>(null)
  const [progress, setProgress] = useState<{ processed: number; total?: number } | null>(null)
  const [status, setStatus] = useState<Status>(null)
  const importing = useRef(false)

  const confirm = async () => {
    if (!file || importing.current) {
      return
    }
    importing.current = true
    setFile(null)
    setProgress({ processed: 0 })
    setStatus(null)
    try {
      const count = await importHistory(file, (processed, total) =>
        setProgress({ processed, total })
      )
      setStatus({ key: count === 1 ? 'historyImportedOne' : 'historyImported', params: { count } })
    } catch {
      setStatus({ key: 'historyImportFailed', error: true })
    } finally {
      importing.current = false
      setProgress(null)
    }
  }

  return {
    file,
    busy: progress !== null,
    progress,
    status,
    select: setFile,
    cancel: () => setFile(null),
    dismiss: () => {
      setFile(null)
      setStatus(null)
    },
    confirm,
  }
}

/** 导入 = 覆盖：用选中文件替换本地全部会话与附件。 */
const ImportHistory = ({
  historyImport,
  disabled,
}: {
  historyImport: ReturnType<typeof useHistoryImport>
  disabled: boolean
}) => {
  const t = useTranslate()
  const inputRef = useRef<HTMLInputElement>(null)
  const { progress } = historyImport

  return (
    <SettingRow
      className={progress ? styles.importing : undefined}
      label={t('historyImport')}
      description={t('historyImportDescription')}
      status={statusText(t, historyImport.status)}
      statusTone={statusTone(historyImport.status)}
      action={
        <>
          <Button
            variant="outlined"
            size="m"
            className={styles.cellButton}
            aria-busy={historyImport.busy}
            aria-label={historyImport.busy ? t('historyImport') : undefined}
            disabled={disabled}
            onClick={() => inputRef.current?.click()}
          >
            {progress ? <IconLoadingOutline16 /> : t('upload')}
          </Button>
          <input
            ref={inputRef}
            type="file"
            accept=".zip,application/zip,application/x-zip-compressed"
            hidden
            onChange={(event) => {
              const file = event.target.files?.[0]
              event.target.value = ''
              if (file) {
                historyImport.select(file)
              }
            }}
          />
        </>
      }
    >
      {progress?.total !== undefined && (
        <div className={styles.importProgress}>
          <div
            className={styles.importTrack}
            role="progressbar"
            aria-label={t('historyImport')}
            aria-valuemin={0}
            aria-valuemax={progress.total}
            aria-valuenow={progress.processed}
          >
            <span
              style={{
                width: `${progress.total ? (progress.processed / progress.total) * 100 : 0}%`,
              }}
            />
          </div>
          <span>
            {progress.processed} / {progress.total}
          </span>
        </div>
      )}
    </SettingRow>
  )
}

/** 将全部会话及图片导出为 ZIP 文件并下载 */
const ExportHistory = ({ disabled }: { disabled: boolean }) => {
  const t = useTranslate()
  const empty = useChatStore((state) => state.sessions.length === 0)
  const [busy, setBusy] = useState(false)
  const [status, setStatus] = useState<Status>(null)

  const onExport = async () => {
    setBusy(true)
    setStatus(null)
    try {
      const { name, blob } = await exportHistory()
      const url = URL.createObjectURL(blob)
      const link = document.createElement('a')
      link.href = url
      link.download = name
      link.click()
      setTimeout(() => URL.revokeObjectURL(url), 10_000)
    } catch (error) {
      setStatus(errorStatus('historyExportFailed', error))
    } finally {
      setBusy(false)
    }
  }

  return (
    <SettingRow
      label={t('exportAllLabel')}
      description={t('historyExportDescription')}
      status={statusText(t, status)}
      statusTone={statusTone(status)}
      action={
        <Button
          variant="outlined"
          size="m"
          className={styles.cellButton}
          disabled={disabled || busy || empty}
          onClick={() => void onExport()}
        >
          {t('exportAllDownload')}
        </Button>
      }
    />
  )
}
